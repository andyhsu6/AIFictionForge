"""档案字段语义的唯一来源（issue #190）。

档案字段的"该写什么"曾经散落在 6 个提示词里（拆书导入、章节续写同步、
旧版批量生成、单角色生成、单组织生成、薄字段补全），改一处就漂一处。
本模块只放**共享规则文本**，所有提示词都从这里拼接，不再各写一份。

两类规则：
- ``FACTS_FIELD_BOUNDARIES``：输出 profile_facts 原子事实的路径使用；
- ``PROSE_FIELD_BOUNDARIES``：输出自由文本档案的旧路径使用。

规则文本里不能出现花括号——它会被 ``str.format`` 渲染，花括号必须留给模板变量。
"""

# 性格的表达形态：必须是能形容人的短语，不能是行为叙述（issue #190 人工评审结论）
TRAIT_FORM_RULE = (
    "**性格必须写成能形容这个人的短语**（形容词、四字词或短谓词），"
    "例如「鄙视江湖人士」「多疑」「隐忍」「护子心切」「外冷内热」。\n"
    "自检：把这条内容接在「他是……」后面要读得通；接不通就是写成了行为，不是在写性格。\n"
    "禁止写成行为描述句：不得用「见……便……」「曾……」「主动……」「……时」「……后」这类句式，"
    "不得写他做了什么、遇到了什么、别人怎么评价他。\n"
    "**意简言赅**：一条只写一个特质，用最短能说清的表达；并列特质最多两个、用顿号分隔。"
    "不要带行为尾巴——「爱子如命，不顾自身伤势」只保留「爱子如命」。\n"
    "**只写已经成立的性情**：尚未发生的事、具体计划与图谋（如「图谋重建魔教」）属于情节，"
    "归 background 或整条不要，不要写进 personality。"
)

# 组织特性：行事风格/价值取向，不是制度条文，也不是首领的个人特质
ORG_TRAIT_RULE = (
    "**组织特性**只写组织的行事风格与价值取向（如「重利轻义」「等级森严」「唯利是图」），"
    "不写门规条文、具体事务、活动范围，也不得把首领或成员的个人特质写成组织特性。"
)

# 事实格式（profile_facts）的字段边界
FACTS_FIELD_BOUNDARIES = (
    "【档案字段定义 - 判断依据只有这一份】\n"
    "档案内容一律写成 profile_facts 原子事实，每条事实归入以下三个字段之一。字段边界是硬约束：\n\n"
    "**personality（性格）**——只收「这个人是什么样的」：性情、脾气、态度、处事风格、价值取向、对他人的惯常反应。\n"
    + TRAIT_FORM_RULE
    + "\n"
    "禁止写入：身份、职务、门派/阵营归属、亲属关系、排行、能力与武力高低、经历事件、外貌。\n\n"
    "**background（背景）**——收「这个人从哪来、是谁、会什么、经历过什么」：\n"
    "出身、师承、身份与归属（门派、职务、排行、家族位置、亲属关系）、经历与遭遇、"
    "能力与实力（如「武功高强」属于本字段，不属于性格）。\n"
    "**不写一次性的临时安排或将发生的事**（如「开学前需回校开会」「准备赴宴」）；"
    "对人物有长期影响的经历与遭遇可以写。\n\n"
    "**appearance（外貌）**——只收外形：体型、容貌、衣着、气质外观。\n"
    "禁止写入：行为、事件、身份、能力。\n"
    "要求：每个实体给 2-4 条，分别覆盖体态身形、面容气色、衣着配饰（有几项写几项，不要为了凑数编造）；"
    "每条 20-45 字，可用一两个逗号连接同类外形细节。不要把外貌压成一条四字短语。\n"
    "**只写跨章稳定的外形**：同一角色在不同章节换了不同衣着时，不要逐套累加（这是场景描写不是外形），"
    "概括成惯常风格（如「常穿浅色衬衫或针织开衫」）或只保留最有辨识度的一两处；"
    "某章临时受伤、淋雨、换装、妆容改变等一次性状态不写。\n\n"
    + ORG_TRAIT_RULE
    + "\n\n"
    "判断口诀：描述「性情」进 personality；描述「是谁/会什么/经历过什么」进 background；"
    "描述「长什么样」进 appearance。拿不准时不要写，宁可少写。"
)

# 自由文本档案（旧路径）的字段边界
PROSE_FIELD_BOUNDARIES = (
    "【档案字段内容要求】\n"
    "1. personality 只写「这个人是什么样的」：性情、脾气、态度、处事风格、价值取向。\n"
    "   " + TRAIT_FORM_RULE.replace("\n", "\n   ") + "\n"
    "2. background 收出身、师承、身份与归属（门派/职务/排行/亲属关系）、经历与遭遇、能力与实力。\n"
    "3. appearance 只收外形（体型、容貌、衣着、气质外观），不写行为与事件。\n"
    "4. " + ORG_TRAIT_RULE + "\n"
    "5. 正文没有明确依据时宁可留空，不要用情节凑数。"
)

